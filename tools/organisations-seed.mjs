// Writes the organisation seed SQL from data/organisations.json (plan section 19). It only writes a file: it never
// touches a database. The seed goes in by migration so ids never change between environments.
//   node tools/organisations-seed.mjs              replace the seed block in migrations/0013_organisations.sql
//                                                  (only before 0013 is applied anywhere that matters)
//   node tools/organisations-seed.mjs --out <file> write the seed alone to a new migration file instead
//   node tools/organisations-seed.mjs --check      exit 1 if the seed block in 0013 is out of date
// Every row is INSERT OR IGNORE, so running a seed again never changes or duplicates an existing organisation.
import fs from 'node:fs';
import { normOrg } from '../worker/org-norm.js';

const ROOT = new URL('../', import.meta.url);
const data = JSON.parse(fs.readFileSync(new URL('data/organisations.json', ROOT), 'utf8'));
const KINDS = ['trust', 'hospital', 'health_board', 'university', 'deanery', 'private', 'other'];
const AT = '2026-10-06T00:00:00Z'; // fixed, so the seed is the same everywhere
const q = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

const ids = new Set();
for (const o of data.organisations) {
  if (!/^wl-\d{1,5}$/.test(o.id)) throw new Error(`Seed ids are wl-1 to wl-99999: ${o.id}`);
  if (ids.has(o.id)) throw new Error(`Duplicate id ${o.id}`);
  if (!KINDS.includes(o.kind)) throw new Error(`Unknown kind ${o.kind} on ${o.id}`);
  if (o.ods && !/^[A-Z0-9]{3,6}$/.test(o.ods)) throw new Error(`Odd ODS code on ${o.id}`);
  ids.add(o.id);
}
for (const o of data.organisations) if (o.parent && !ids.has(o.parent)) throw new Error(`Unknown parent ${o.parent} on ${o.id}`);

const lines = ['-- BEGIN SEED (generated by tools/organisations-seed.mjs from data/organisations.json; do not edit by hand)'];
for (const o of data.organisations) {
  lines.push(`INSERT OR IGNORE INTO organisations (id, name, name_norm, kind, parent_id, country, status, source, ods_code, created_at, updated_at) VALUES (${[o.id, o.name, normOrg(o.name), o.kind, o.parent || null, o.country || 'GB', 'active', 'seed', o.ods || null, AT, AT].map(q).join(', ')});`);
}
for (const o of data.organisations) {
  const seen = new Set([normOrg(o.name)]);
  for (const a of o.aliases || []) {
    const n = normOrg(a);
    if (!n || seen.has(n)) continue;
    seen.add(n);
    lines.push(`INSERT OR IGNORE INTO organisation_aliases (organisation_id, alias, alias_norm, created_at) VALUES (${[o.id, a, n, AT].map(q).join(', ')});`);
  }
}
lines.push('-- END SEED');
const seed = lines.join('\n') + '\n';

const args = process.argv.slice(2);
const outAt = args.indexOf('--out');
if (outAt >= 0) {
  const file = args[outAt + 1];
  if (!file) { console.error('Usage: --out <file>'); process.exit(2); }
  fs.writeFileSync(file, `-- Organisation seed from data/organisations.json. Additive only.\n${seed}`);
  console.log(`Wrote ${file}`);
} else {
  const mig = new URL('migrations/0013_organisations.sql', ROOT);
  const text = fs.readFileSync(mig, 'utf8');
  const re = /-- BEGIN SEED[\s\S]*?-- END SEED\n?/;
  if (!re.test(text)) { console.error('No seed block in 0013_organisations.sql'); process.exit(1); }
  const next = text.replace(re, seed);
  if (args.includes('--check')) {
    if (next !== text) { console.error('The seed in 0013_organisations.sql is out of date. Run node tools/organisations-seed.mjs'); process.exit(1); }
    console.log('Seed up to date.');
  } else {
    fs.writeFileSync(mig, next);
    console.log(`Seed: ${data.organisations.length} organisations.`);
  }
}
